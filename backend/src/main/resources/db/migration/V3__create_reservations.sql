CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id BIGINT NOT NULL REFERENCES spaces(id),
    booker_name VARCHAR(100) NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT reservations_booker_not_blank CHECK (booker_name ~ '[^[:space:]]'),
    CONSTRAINT reservations_valid_interval CHECK (start_at < end_at),
    CONSTRAINT reservations_valid_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT reservations_cancellation_consistent CHECK (
        (status = 'CONFIRMED' AND cancelled_at IS NULL) OR
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
    )
);

CREATE INDEX reservations_space_status_start_idx ON reservations(space_id, status, start_at);
